-- One final rating per movie, as stated in the Sprint 02 business rules.
-- The rating scale depends on the source; validate or normalize during ingestion.
CREATE TABLE ratings (
    rating_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id INTEGER NOT NULL UNIQUE REFERENCES movies(movie_id),
    rating_source TEXT NOT NULL,
    rating_value INTEGER NOT NULL CHECK (rating_value >= 0)
);

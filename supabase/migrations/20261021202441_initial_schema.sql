-- Each genre is represented once; names are unique for consistent classification.
CREATE TABLE genres (
    genre_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name TEXT NOT NULL UNIQUE
);

-- One row per film. IDs can be populated from the selected source or generated locally.
CREATE TABLE movies (
    movie_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    release_date DATE,
    runtime INTEGER CHECK (runtime IS NULL OR runtime > 0)
);

-- A single person can appear as an actor and/or crew member.
CREATE TABLE people (
    person_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);

-- A studio may be associated with multiple movies.
CREATE TABLE studios (
    studio_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studio_name VARCHAR(250) NOT NULL
);

-- One row per performer per movie; character_name may be unavailable.
CREATE TABLE movie_cast (
    movie_id INTEGER NOT NULL REFERENCES movies(movie_id),
    person_id INTEGER NOT NULL REFERENCES people(person_id),
    character_name TEXT,
    PRIMARY KEY (movie_id, person_id)
);

-- Job is part of the key so a person can hold multiple crew roles on one movie.
CREATE TABLE movie_crew (
    movie_id INTEGER NOT NULL REFERENCES movies(movie_id),
    person_id INTEGER NOT NULL REFERENCES people(person_id),
    job TEXT NOT NULL,
    PRIMARY KEY (movie_id, person_id, job)
);

-- Many-to-many link: a movie can belong to several genres.
CREATE TABLE movie_genres (
    movie_id INTEGER NOT NULL REFERENCES movies(movie_id),
    genre_id INTEGER NOT NULL REFERENCES genres(genre_id),
    PRIMARY KEY (movie_id, genre_id)
);

-- Many-to-many link: movies may have multiple production studios.
CREATE TABLE movie_studios (
    movie_id INTEGER NOT NULL REFERENCES movies(movie_id),
    studio_id INTEGER NOT NULL REFERENCES studios(studio_id),
    PRIMARY KEY (movie_id, studio_id)
);

-- One final rating per movie, as stated in the Sprint 02 business rules.
-- The rating scale depends on the source; validate or normalize during ingestion.
CREATE TABLE ratings (
    rating_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id INTEGER NOT NULL UNIQUE REFERENCES movies(movie_id),
    rating_source TEXT NOT NULL,
    rating_value INTEGER NOT NULL CHECK (rating_value >= 0)
);

-- A movie can have multiple individual reviews.
-- review_score is optional because some sources supply text only.
CREATE TABLE reviews (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id INTEGER NOT NULL REFERENCES movies(movie_id),
    review_source VARCHAR(150) NOT NULL,
    review_text TEXT,
    review_score NUMERIC(6,2) CHECK (review_score IS NULL OR review_score >= 0),
    CHECK (review_text IS NOT NULL OR review_score IS NOT NULL)
);
